/**
 * Render every meaningful task — done and active — in first-appearance order.
 * A finished task is still part of the title; it is never an implicit deletion.
 * If more subjects exist than the fragment limit allows, the caller fails closed.
 *
 * The implementation lives in `title-format.mjs` and is the only renderer.
 */
function renderTitleWith(tasks, opts) {
  return renderTitleTasks(tasks, opts);
}

/**
 * Program-side title rendering:
 *   [对象](动作)任务
 *   [对象](动作)任务1;(动作)任务2
 *   [对象1](动作)任务1 | [对象2](动作)任务2
 */
export function renderTitle(tasks, options = {}) {
  const opts = normalizeOptions(options);
  return renderTitleWith(sanitizeLedger(tasks, opts, []), opts);
}

